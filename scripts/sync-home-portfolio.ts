async function sync() {
  console.log("1. Buscando documentos antigos na coleção portfolio_projects...");
  const snap = await getDocs(collection(db, "portfolio_projects"));
  console.log(`Encontrados ${snap.docs.length} documentos existentes.`);

  for (const d of snap.docs) {
    console.log(`Removendo documento antigo: ${d.id} (${d.data().name || d.data().title})`);
    await deleteDoc(doc(db, "portfolio_projects", d.id));
  }

  console.log("\n2. Inserindo os 7 projetos reais da Home anterior com vídeos, links e thumbs...");
  for (const proj of REAL_HOME_PROJECTS) {
    const { id, ...data } = proj;
    console.log(`Inserindo projeto: ${proj.client} - ${proj.title}`);
    await setDoc(doc(db, "portfolio_projects", id), {
      ...data,
      createdAt: serverTimestamp(),
    });
  }

  console.log("\n✅ Sincronização concluída com sucesso!");
  process.exit(0);
}

sync().catch((err) => {
  console.error("Erro na sincronização:", err);
  process.exit(1);
});
